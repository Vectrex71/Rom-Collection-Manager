export function getPlatformByExtension(ext: string): PlatformCode {
  const normalized = ext.toLowerCase().startsWith('.') ? ext.toLowerCase() : `.${ext.toLowerCase()}`;
  // Generic container formats (like .zip, .7z, .rar, .bin, .iso, .cue, .chd) are shared by multiple systems
  // and must NOT be eagerly claimed by the first arcade/mame entry in PLATFORMS!
  const GENERIC_EXTENSIONS = ['.zip', '.7z', '.rar', '.bin', '.iso', '.cue', '.chd', '.img', '.tar', '.gz'];
  if (GENERIC_EXTENSIONS.includes(normalized)) {
    return 'OTHER';
  }

  for (const plat of PLATFORMS) {
    if (plat.extensions.includes(normalized)) {
      return plat.id;
    }
  }
  return 'OTHER';
}

export function getPlatformMetadata(id: PlatformCode): PlatformMetadata | undefined {
  return PLATFORMS.find((p) => p.id === id);
}
